const fs = require("fs");
const path = require("path");
const YAML = require("yaml");
const { splitAggregateSpec } = require("./split-aggregate-openapi");
const { writeGeneratedFiles: writeGeneratedOperationRouteFiles } = require("./generate-operation-routes");
const { writeGeneratedPageModelArtifacts } = require("./generate-page-models");

const ROOT = path.resolve(__dirname, "..");

const OPENAPI_SOURCES = [
  {
    name: "fastnear",
    src: path.resolve(ROOT, "../fn/fastnear-api-server-rs/openapi/openapi.yaml"),
    dest: path.resolve(ROOT, "apis/fastnear"),
  },
  {
    name: "transactions",
    src: path.resolve(ROOT, "../fn/explorer-api/openapi/openapi.yaml"),
    dest: path.resolve(ROOT, "apis/transactions"),
  },
  {
    name: "transfers",
    src: path.resolve(ROOT, "../fn/transfers-api/openapi/openapi.yaml"),
    dest: path.resolve(ROOT, "apis/transfers"),
  },
  {
    name: "kv-fastdata",
    src: path.resolve(ROOT, "../fn/kv-fastdata-server/openapi/openapi.yaml"),
    dest: path.resolve(ROOT, "apis/kv-fastdata"),
  },
  {
    name: "neardata",
    src: path.resolve(ROOT, "../fn/neardata-server/openapi/openapi.yaml"),
    dest: path.resolve(ROOT, "apis/neardata"),
  },
];

const ENHANCEMENTS_ROOT = path.resolve(ROOT, "enhancements");

const GENERATED_ENHANCEMENTS_MODULE = path.resolve(
  ROOT,
  "@theme/ext/generatedEnhancements.ts"
);

function readAggregateSpec({ name, src, dest }) {
  if (fs.existsSync(src)) {
    const parsed = YAML.parse(fs.readFileSync(src, "utf8"));
    console.log(`Synced ${name} aggregate OpenAPI: ${src} -> ${dest}`);
    return parsed;
  }

  const vendoredAggregate = path.join(dest, "openapi.yaml");
  if (fs.existsSync(vendoredAggregate)) {
    console.warn(
      `Using vendored ${name} aggregate OpenAPI; external source is unavailable: ${src}`
    );
    return YAML.parse(fs.readFileSync(vendoredAggregate, "utf8"));
  }

  throw new Error(
    `Missing aggregate OpenAPI source for ${name}: ${src}\n` +
      `No vendored fallback exists at ${vendoredAggregate}.`
  );
}

function writeEnhancementsModule() {
  const manifests = {};

  if (fs.existsSync(ENHANCEMENTS_ROOT)) {
    const services = fs
      .readdirSync(ENHANCEMENTS_ROOT, { withFileTypes: true })
      .filter((entry) => entry.isDirectory())
      .map((entry) => entry.name)
      .sort();

    for (const service of services) {
      const manifestPath = path.join(ENHANCEMENTS_ROOT, service, "manifest.yaml");
      if (!fs.existsSync(manifestPath)) {
        continue;
      }

      const parsed = YAML.parse(fs.readFileSync(manifestPath, "utf8"));
      if (parsed) {
        manifests[service] = parsed;
      }
    }
  }

  fs.mkdirSync(path.dirname(GENERATED_ENHANCEMENTS_MODULE), { recursive: true });
  fs.writeFileSync(
    GENERATED_ENHANCEMENTS_MODULE,
    [
      "/* This file is auto-generated by scripts/sync-external-apis.js. */",
      "/* Do not edit it by hand; update the portal-owned manifests in enhancements/<service>/manifest.yaml instead. */",
      "",
      `export const DOCS_ENHANCEMENTS = ${JSON.stringify(manifests, null, 2)} as const;`,
      "",
      "export type DocsEnhancementsMap = typeof DOCS_ENHANCEMENTS;",
      "",
    ].join("\n")
  );
  console.log(`Generated enhancements module: ${GENERATED_ENHANCEMENTS_MODULE}`);
}

for (const source of OPENAPI_SOURCES) {
  const aggregateSpec = readAggregateSpec(source);
  splitAggregateSpec(aggregateSpec, source.dest);
  console.log(`Generated ${source.name} portal leaf specs: ${source.dest}`);
}

writeEnhancementsModule();
writeGeneratedOperationRouteFiles();
writeGeneratedPageModelArtifacts();
